function translateName(englishName) {
  // Check full name map first
  if (FULL_NAME_MAP[englishName]) {
    return FULL_NAME_MAP[englishName];
  }

  // Apply phrase rules
  let translated = englishName;
  for (const [eng, ptbr] of PHRASE_RULES) {
    const regex = new RegExp(eng.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'), 'gi');
    translated = translated.replace(regex, ptbr);
  }

  return translated;
}

// ─── Main ──────────────────────────────────────────────────────────────────────
async function main() {
  const url = (process.env.TURSO_DATABASE_URL || '').replace(/[\r\n\s]/g, '').replace(/\\r\\n/g, '');
  const authToken = (process.env.TURSO_AUTH_TOKEN || '').replace(/[\r\n\s]/g, '').replace(/\\r\\n/g, '');

  if (!url || !authToken) {
    console.error('❌ Missing TURSO_DATABASE_URL or TURSO_AUTH_TOKEN');
    process.exit(1);
  }

  console.log(`🔗 Connecting to: ${url}`);
  const client = createClient({ url, authToken });

  // 1. Fetch all system exercises
  console.log('📥 Fetching system exercises...');
  const result = await client.execute(
    "SELECT id, name FROM exercises WHERE trainer_id IS NULL"
  );
  console.log(`  ✅ ${result.rows.length} exercises found`);

  // 2. Translate and prepare updates
  let translated = 0;
  let unchanged = 0;
  const updates = [];

  for (const row of result.rows) {
    const newName = translateName(row.name);
    if (newName !== row.name) {
      updates.push({ id: row.id, oldName: row.name, newName });
      translated++;
    } else {
      unchanged++;
    }
  }

  console.log(`\n📊 Translation summary:`);
  console.log(`  ✅ ${translated} exercises to translate`);
  console.log(`  ⏭️  ${unchanged} exercises already in Portuguese or unchanged`);

  // Show some examples
  console.log('\n📝 Translation examples:');
  for (const u of updates.slice(0, 20)) {
    console.log(`  "${u.oldName}" → "${u.newName}"`);
  }

  // 3. Apply updates in batches
  console.log('\n🔄 Updating database...');
  const BATCH_SIZE = 50;
  let done = 0;

  for (let i = 0; i < updates.length; i += BATCH_SIZE) {
    const batch = updates.slice(i, i + BATCH_SIZE);
    const stmts = batch.map(u => ({
      sql: "UPDATE exercises SET name = ?, updated_at = strftime('%s', 'now') WHERE id = ?",
      args: [u.newName, u.id],
    }));

    await client.batch(stmts, 'write');
    done += batch.length;
    process.stdout.write(`  📦 ${done}/${updates.length} updated\r`);
  }

  console.log(`\n✅ Done! Updated ${done} exercise names to Portuguese.`);

  // 4. Verification — show some samples
  const samples = await client.execute(
    "SELECT name, muscle_group FROM exercises WHERE trainer_id IS NULL ORDER BY name LIMIT 15"
  );
  console.log('\n🏋️ Sample exercises (after translation):');
  for (const row of samples.rows) {
    console.log(`  • ${row.name} [${row.muscle_group}]`);
  }
}

main().catch((err) => {
  console.error('❌ Fatal error:', err);
  process.exit(1);
});
